<?php

declare(strict_types=1);

namespace App\Domain\Blocks\TestGenerator\Arithmetic;

/**
 * Базовый узел дерева арифметического выражения.
 *
 * Дерево используется для двух целей:
 *  1. корректный рендер в LaTeX с расстановкой скобок по приоритетам
 *     операций (см. BinaryNode::renderChild());
 *  2. пошаговое решение через ArithmeticSolver (сворачивание узлов
 *     с числовыми детьми).
 *
 * Значения намеренно ограничены int|float: генератор арифметики
 * строит выражения только с целочисленными операндами и целочисленным
 * результатом деления (делимое кратно делителю), поэтому на практике
 * evaluate() всегда возвращает int. Тип float оставлен для расширяемости
 * (например, если появится генератор дробей).
 */
abstract class ExprNode
{
    /**
     * Рендер в LaTeX без внешних скобок.
     * Скобки добавляет родитель через BinaryNode::renderChild(),
     * зная свой приоритет.
     */
    abstract public function toLatex(): string;

    /**
     * Вычисление значения поддерева.
     */
    abstract public function evaluate(): int|float;

    /**
     * Приоритет операции.
     *
     * Возвращает:
     *  - PHP_INT_MAX для чисел (атом — скобки не нужны никогда);
     *  - 2 для '*' и '/';
     *  - 1 для '+' и '-'.
     *
     * Используется в BinaryNode::renderChild() для решения,
     * нужно ли оборачивать ребёнка в \left( ... \right).
     */
    abstract public function precedence(): int;
}
