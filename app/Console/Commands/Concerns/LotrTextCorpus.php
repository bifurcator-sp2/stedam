    protected function randomPlainText(int $min = 3, int $max = 6): string
    {
        $n = random_int($min, $max);
        $parts = [];
        for ($i = 0; $i < $n; $i++) {
            $parts[] = rtrim($this->pick($this->blockSentences), '.!?');
        }

        return implode('. ', $parts) . '.';
    }

    protected function randomHtml(int $min = 2, int $max = 4): string
    {
        $n = random_int($min, $max);
        $paras = [];
        for ($i = 0; $i < $n; $i++) {
            $sentences = [];
            $m = random_int(2, 4);
            for ($j = 0; $j < $m; $j++) {
                $sentences[] = $this->pick($this->blockSentences);
            }
            $paras[] = '<p>' . implode(' ', $sentences) . '</p>';
        }

        return implode("\n", $paras);
    }

    protected function pick(array $arr)
    {
        return $arr[array_rand($arr)];
    }
