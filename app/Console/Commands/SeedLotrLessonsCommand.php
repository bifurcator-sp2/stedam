    // ============================================================
    // Точка входа
    // ============================================================

    public function handle(): int
    {
        $this->stopFile  = $this->option('stop-file') ?: null;
        $this->chunkSize = max(1, (int) $this->option('chunk'));
        $this->installSignalHandlers();

        $userId    = (int) $this->option('user');
        $count     = (int) $this->option('count');
        $minBlocks = (int) $this->option('min-blocks');
        $maxBlocks = (int) $this->option('max-blocks');
        $keep      = (bool) $this->option('keep');

        if ($count < 1) {
            $this->error('--count must be >= 1');
            return self::FAILURE;
        }
        if ($minBlocks < 1 || $maxBlocks < $minBlocks) {
            $this->error('Invalid --min-blocks / --max-blocks');
            return self::FAILURE;
        }

        $lessonTotal = Lesson::withTrashed()->count();
        $blockTotal  = LessonBlock::withTrashed()->count();

        if (!$keep) {
            if (!$this->option('force') && !$this->option('safe')) {
                if (!$this->confirm(
                    "This will DELETE {$lessonTotal} lessons and {$blockTotal} lesson_blocks ".
                    "for user {$userId}, then seed {$count} fresh lessons. Continue?"
                )) {
                    return self::SUCCESS;
                }
            }
            $this->deleteAllLessons();
        }

        $blocks = Block::query()->get();
        if ($blocks->isEmpty()) {
            $this->error('No blocks found in `blocks` table. Nothing to use as template.');
            return self::FAILURE;
        }
        $this->info("Blocks available: {$blocks->count()}");

        $leaves = $this->leafIds($userId);
        if (empty($leaves)) {
            $this->error("No leaf taxonomies found for user {$userId}");
            return self::FAILURE;
        }
        $this->info("Leaf taxonomies: " . count($leaves));

        // кэшируем схемы по code
        foreach ($blocks as $block) {
            if (!isset($this->schemaCache[$block->code])) {
                $this->schemaCache[$block->code] = BlockSettingsRegistry::serializeSchema($block->code) ?: [];
            }
        }

        $distribution = $this->distribute($count, count($leaves));
        $bar = $this->output->createProgressBar($count);
        $bar->start();

        $created = 0;
        $stopped = false;

        foreach ($leaves as $i => $leafId) {
            if ($this->shouldStop()) {
                $stopped = true;
                break;
            }

            $n = $distribution[$i];
            if ($n <= 0) {
                continue;
            }

            for ($off = 0; $off < $n; $off += $this->chunkSize) {
                if ($this->shouldStop()) {
                    $stopped = true;
                    break 2;
                }

                $chunk = min($this->chunkSize, $n - $off);
                $done  = $this->createChunk($leafId, $chunk, $userId, $blocks, $minBlocks, $maxBlocks);

                $created += $done;
                $bar->advance($done);

                // Если внутри createChunk сработал стоп — выходим из всех циклов
                if ($done < $chunk) {
                    $stopped = true;
                    break 2;
                }
            }
        }

        $bar->finish();
        $this->newLine(2);

        if ($stopped) {
            $this->warn("Остановлено. Создано {$created} из {$count} уроков.");
            $this->line('Данные консистентны: последний чанк закоммичен, буферы сброшены.');
            return self::SUCCESS;
        }

        $this->info("Done. Created {$created} lessons.");

        return self::SUCCESS;
    }

    // ============================================================
    // Graceful stop
    // ============================================================

    protected function installSignalHandlers(): void
    {
        if (!function_exists('pcntl_signal') || !function_exists('pcntl_async_signals')) {
            $this->warn('pcntl недоступен (Windows?) — Ctrl+C завершит процесс жёстко. Используйте --stop-file.');
            return;
        }

        pcntl_async_signals(true);

        $onStop = function (string $label) {
            if ($this->stopRequested) {
                $this->newLine();
                $this->warn("Повторный {$label} — принудительный выход (текущий чанк откатится).");
                exit(130);
            }
            $this->stopRequested = true;
            $this->newLine();
            $this->warn("{$label}: завершаю текущий чанк и корректно выхожу. Повторный {$label} — форс-выход.");
        };

        pcntl_signal(SIGINT,  fn () => $onStop('SIGINT'));
        pcntl_signal(SIGTERM, fn () => $onStop('SIGTERM'));
    }

    protected function shouldStop(): bool
    {
        if ($this->stopRequested) {
            return true;
        }
        if ($this->stopFile && file_exists($this->stopFile)) {
            $this->stopRequested = true;
            return true;
        }
        return false;
    }

    // ============================================================
    // Удаление
    // ============================================================

    protected function deleteAllLessons(): void
    {
        if ($this->option('safe')) {
            $this->deleteSafe();
        } else {
            $this->deleteFast();
        }
    }

    /**
     * Быстрое удаление: TRUNCATE. Модельные события НЕ срабатывают,
     * файлы в storage могут остаться сиротами. Приемлемо для локальной разработки.
     */
    protected function deleteFast(): void
    {
        $this->info('Fast delete (TRUNCATE)...');

        $hadForeign = false;
        try {
            DB::statement('SET FOREIGN_KEY_CHECKS=0');
            $hadForeign = true;

            if (Schema::hasTable('lesson_taxonomy')) {
                DB::table('lesson_taxonomy')->truncate();
            }
            if (Schema::hasTable('lesson_blocks')) {
                DB::table('lesson_blocks')->truncate();
            }
            if (Schema::hasTable('lessons')) {
                DB::table('lessons')->truncate();
            }
        } finally {
            if ($hadForeign) {
                DB::statement('SET FOREIGN_KEY_CHECKS=1');
            }
        }

        $this->cleanupOrphanFileSets();
        $this->warn('Note: storage files may remain orphaned. Use --safe for full cleanup.');
    }

    /**
     * Безопасное удаление: по одной модели, с событиями (включая FileSet cascade).
     * Медленно на больших объёмах.
     */
    protected function deleteSafe(): void
    {
        $this->info('Safe delete (per-model, this may take a while)...');
        $total = Lesson::withTrashed()->count();
        $bar = $this->output->createProgressBar(max(1, $total));
        $bar->start();

        Lesson::withTrashed()->chunkById(50, function ($lessons) use ($bar) {
            foreach ($lessons as $lesson) {
                try {
                    $lesson->taxonomies()->detach();

                    // Удаляем блоки по одному, чтобы сработали события HasFileSets
                    $lesson->blocks()->withTrashed()->get()->each(function ($block) {
                        $block->forceDelete();
                    });

                    $lesson->forceDelete();
                    $bar->advance();
                } catch (\Throwable $e) {
                    $this->newLine();
                    $this->warn("Failed to delete lesson {$lesson->id}: {$e->getMessage()}");
                }
            }
        });

        $bar->finish();
        $this->newLine();

        $this->cleanupOrphanFileSets();
    }

    /**
     * Убирает осиротевшие FileSet-записи для LessonBlock (без удаления файлов на диске).
     * Работает, только если существует таблица `file_sets`.
     */
    protected function cleanupOrphanFileSets(): void
    {
        if (!Schema::hasTable('file_sets') || !Schema::hasTable('lesson_blocks')) {
            return;
        }

        try {
            $deleted = DB::table('file_sets')
                ->where('model', LessonBlock::class)
                ->whereNotExists(function ($q) {
                    $q->select(DB::raw(1))
                        ->from('lesson_blocks')
                        ->whereColumn('lesson_blocks.id', 'file_sets.model_id');
                })
                ->delete();

            if ($deleted > 0) {
                $this->info("Cleaned {$deleted} orphan file_set rows.");
            }
        } catch (\Throwable $e) {
            $this->warn("FileSet cleanup skipped: {$e->getMessage()}");
        }
    }

