    // Создание
    // ============================================================

    /**
     * Создаёт один чанк уроков в рамках одной транзакции.
     * Возвращает число реально созданных уроков (может быть < $n, если сработал стоп).
     */
    protected function createChunk(
        int $leafId,
        int $n,
        int $userId,
        $blocks,
        int $minBlocks,
        int $maxBlocks
    ): int {
        $created = 0;

        DB::transaction(function () use ($leafId, $n, $userId, $blocks, $minBlocks, $maxBlocks, &$created) {
            $now = now();

            for ($i = 0; $i < $n; $i++) {
                if ($this->shouldStop()) {
                    break; // текущий урок ещё не начат — безопасно
                }

                $ts = $now->copy()->subMinutes(random_int(0, 60 * 24 * 90));

                $lessonId = DB::table('lessons')->insertGetId([
                    'user_id'     => $userId,
                    'locale'      => 'ru',
                    'saved'       => true,
                    'title'       => $this->pick($this->lessonTitles),
                    'description' => $this->pick($this->lessonDescriptions),
                    'published'   => true,
                    'created_at'  => $ts,
                    'updated_at'  => $ts,
                ]);

                $blockCount = random_int($minBlocks, $maxBlocks);

                for ($j = 0; $j < $blockCount; $j++) {
                    /** @var Block $block */
                    $block = $blocks->random();
                    $settings = $this->buildSettingsForBlock($block);

                    $this->pendingBlocks[] = [
                        'user_id'    => $userId,
                        'block_id'   => $block->id,
                        'lesson_id'  => $lessonId,
                        'order'      => $j,
                        'settings'   => json_encode(
                            $settings,
                            JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
                        ),
                        'created_at' => $ts,
                        'updated_at' => $ts,
                    ];

                    if (count($this->pendingBlocks) >= $this->pivotBufferLimit) {
                        $this->flushBuffers();
                    }
                }

                $this->pendingPivots[] = [
                    'lesson_id'   => $lessonId,
                    'taxonomy_id' => $leafId,
                ];

                if (count($this->pendingPivots) >= $this->pivotBufferLimit) {
                    $this->flushBuffers();
                }

                $created++;
            }

            // Всегда сбрасываем буфер внутри транзакции — иначе уроки без блоков.
            $this->flushBuffers();
        });

        return $created;
    }

    protected function flushBuffers(): void
    {
        if (!empty($this->pendingBlocks)) {
            DB::table('lesson_blocks')->insert($this->pendingBlocks);
            $this->pendingBlocks = [];
        }
        if (!empty($this->pendingPivots)) {
            DB::table('lesson_taxonomy')->insert($this->pendingPivots);
            $this->pendingPivots = [];
        }
    }

    // ============================================================
    // Сборка settings для блока
    // ============================================================

    /**
     * Полный клон настроек блока-прототипа с подменой default
     * только у контентных узлов (title / summary / text / htmltext).
     * Галереи и image-узлы не изменяются.
     */
    protected function buildSettingsForBlock(Block $block): array
    {
        // 1. «Прототип»: настройки самого блока; если пусто — сериализованная схема.
        $protoSettings = $block->settings;
        if (!is_array($protoSettings) || empty($protoSettings)) {
            $protoSettings = $this->schemaCache[$block->code] ?? [];
        }
        if (empty($protoSettings)) {
            return [];
        }

        // 2. Полный клон настроек прототипа.
        //    В PHP массивы копируются по значению (copy-on-write),
        //    поэтому обычного присваивания достаточно для полного клона.
        $newSettings = $protoSettings;

        // 3. Заполняем ТОЛЬКО контентные узлы: title / summary / text / htmltext.
        //    Галереи, image-узлы и всё остальное — без изменений.
        $newSettings = $this->fillContentDefaultsOnly($newSettings);

        // 4. Прогон через нормализатор: остаются только public-узлы
        //    с их default. Форма гарантированно совпадает (клон),
        //    но на всякий случай ловим исключения.
        try {
            return SettingsNormalizer::extractPublicDefaults($newSettings, $protoSettings);
        } catch (SettingsShapeException $e) {
            $this->newLine();
            $this->warn("  ! Block {$block->id} ({$block->code}) shape: " . $e->getMessage());
            return [];
        } catch (\Throwable $e) {
            $this->newLine();
            $this->warn("  ! Block {$block->id} ({$block->code}): " . $e->getMessage());
            return [];
        }
    }

    /**
     * Рекурсивно обходит дерево настроек и перезаписывает default
     * ТОЛЬКО у контентных узлов.
     *
     * Обрабатываемые узлы:
     *  - key='title'    → blockTitles
     *  - key='summary'  → blockSummaries
     *  - key='text'     → randomPlainText()
     *  - key='htmltext' или type='htmltext' → randomHtml()
     *
     * Правила:
     *  - если у узла явно указан type и он не 'string' (и не 'htmltext'),
     *    узел считается контейнером и не трогается;
     *  - если type отсутствует (settings уже в «сокращённой» форме
     *    от extractPublicDefaults) — обрабатываем по key;
     *  - image-узлы и галереи не изменяем вообще.
     */
    protected function fillContentDefaultsOnly(array $node): array
    {
        // Сначала обходим детей — порядок не важен, но так читается проще.
        if (!empty($node['children']) && is_array($node['children'])) {
            foreach ($node['children'] as $i => $child) {
                if (is_array($child)) {
                    $node['children'][$i] = $this->fillContentDefaultsOnly($child);
                }
            }
        }

        $key  = $node['key']  ?? null;
        $type = $node['type'] ?? null;

        // htmltext — по ключу узла или по типу узла.
        $isHtmltext = ($key === 'htmltext') || ($type === 'htmltext');

        if ($isHtmltext) {
            $node['default'] = $this->randomHtml();
            return $node;
        }

        // Явный не-string тип — контейнер, не контентный лист. Пропускаем.
        if ($type !== null && $type !== 'string') {
            return $node;
        }

        switch ($key) {
            case 'title':
                $node['default'] = $this->pick($this->blockTitles);
                break;
            case 'summary':
                $node['default'] = $this->pick($this->blockSummaries);
                break;
            case 'text':
                $node['default'] = $this->randomPlainText();
                break;
        }

        return $node;
    }

    // ============================================================
    // Утилиты
    // ============================================================

    protected function leafIds(int $userId): array
    {
        return DB::table('taxonomies')
            ->whereNull('deleted_at')
            ->where('user_id', $userId)
            ->whereNotExists(function ($q) {
                $q->select(DB::raw(1))
                    ->from('taxonomies as t_child')
                    ->whereColumn('t_child.parent_id', 'taxonomies.id')
                    ->whereNull('t_child.deleted_at');
            })
            ->orderBy('id')
            ->pluck('id')
            ->all();
    }

    protected function distribute(int $total, int $buckets): array
    {
        $base = intdiv($total, $buckets);
        $rem  = $total % $buckets;
        $arr  = array_fill(0, $buckets, $base);
        for ($i = 0; $i < $rem; $i++) {
            $arr[$i]++;
        }
        return $arr;
    }

    protected function randomPlainText(int $min = 3, int $max = 6): string
    {
        $n = random_int($min, $max);
        $parts = [];
        for ($i = 0; $i < $n; $i++) {
            $parts[] = rtrim($this->pick($this->blockSentences), '.!?');
        }
        return implode('. ', $parts) . '.';
    }

    protected function randomHtml(int $min = 2, int $max = 4): string
    {
        $n = random_int($min, $max);
        $paras = [];
        for ($i = 0; $i < $n; $i++) {
            $sentences = [];
            $m = random_int(2, 4);
            for ($j = 0; $j < $m; $j++) {
                $sentences[] = $this->pick($this->blockSentences);
            }
            $paras[] = '<p>' . implode(' ', $sentences) . '</p>';
        }
        return implode("\n", $paras);
    }

    protected function pick(array $arr)
    {
        return $arr[array_rand($arr)];
    }
