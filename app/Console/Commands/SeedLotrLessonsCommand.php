    protected function deleteAllLessons(): void
    {
        if ($this->option('safe')) {
            $this->deleteSafe();
        } else {
            $this->deleteFast();
        }
    }

    /**
     * Быстрое удаление уроков.
     *
     * ВАЖНО: TRUNCATE здесь неприменим.
     *   - TRUNCATE не умеет WHERE — он сносит таблицу целиком.
     *   - В lesson_blocks лежат И собственные блоки уроков (lesson_id = N),
     *     И глобальные задания (lesson_id IS NULL). TRUNCATE lesson_blocks
     *     уничтожит задания.
     *   - TRUNCATE lessons CASCADE тоже не годится: CASCADE находит
     *     lesson_blocks по FK и сносит её целиком — по той же причине.
     *
     * Поэтому удаляем явным DELETE в правильном порядке:
     *   1. привязки заданий к урокам (lesson_lesson_block_as_test)
     *   2. привязки уроков к таксономиям (lesson_taxonomy)
     *   3. собственные блоки уроков (lesson_blocks WHERE lesson_id IS NOT NULL)
     *   4. сами уроки (lessons)
     *
     * Глобальные задания (lesson_blocks WHERE lesson_id IS NULL) и их
     * привязки (lesson_block_taxonomy) НЕ трогаются.
     */
    protected function deleteFast(): void
    {
        $this->info('Fast delete (DELETE)...');

        DB::transaction(function () {
            $purged = [];

            if (Schema::hasTable('lesson_lesson_block_as_test')) {
                $purged['lesson_lesson_block_as_test'] = DB::table('lesson_lesson_block_as_test')->delete();
            }

            if (Schema::hasTable('lesson_taxonomy')) {
                $purged['lesson_taxonomy'] = DB::table('lesson_taxonomy')->delete();
            }

            // Только собственные блоки уроков. Глобальные задания
            // (lesson_id IS NULL) сохраняются.
            if (Schema::hasTable('lesson_blocks')) {
                $purged['lesson_blocks'] = DB::table('lesson_blocks')
                    ->whereNotNull('lesson_id')
                    ->delete();
            }

            if (Schema::hasTable('lessons')) {
                $purged['lessons'] = DB::table('lessons')->delete();
            }

            if (!empty($purged)) {
                $summary = [];
                foreach ($purged as $table => $count) {
                    $summary[] = "{$table}={$count}";
                }
                $this->line('Удалено: ' . implode(', ', $summary));
            }
        });

        $this->cleanupOrphanFileSets();
    }

    /**
     * Безопасное удаление: по одной модели, с событиями (включая FileSet cascade).
     * Медленно на больших объёмах.
     */
    protected function deleteSafe(): void
    {
        $this->info('Safe delete (per-model, this may take a while)...');
        $total = Lesson::withTrashed()->count();
        $bar = $this->output->createProgressBar(max(1, $total));
        $bar->start();

        Lesson::withTrashed()->chunkById(50, function ($lessons) use ($bar) {
            foreach ($lessons as $lesson) {
                try {
                    $lesson->taxonomies()->detach();

                    // Удаляем блоки по одному, чтобы сработали события HasFileSets
                    $lesson->blocks()->withTrashed()->get()->each(function ($block) {
                        $block->forceDelete();
                    });

                    $lesson->forceDelete();
                    $bar->advance();
                } catch (\Throwable $e) {
                    $this->newLine();
                    $this->warn("Failed to delete lesson {$lesson->id}: {$e->getMessage()}");
                }
            }
        });

        $bar->finish();
        $this->newLine();

        $this->cleanupOrphanFileSets();
    }

    /**
     * Убирает осиротевшие FileSet-записи для LessonBlock (без удаления файлов на диске).
     * Работает, только если существует таблица `file_sets`.
     */
    protected function cleanupOrphanFileSets(): void
    {
        if (!Schema::hasTable('file_sets') || !Schema::hasTable('lesson_blocks')) {
            return;
        }

        try {
            $deleted = DB::table('file_sets')
                ->where('model', LessonBlock::class)
                ->whereNotExists(function ($q) {
                    $q->select(DB::raw(1))
                        ->from('lesson_blocks')
                        ->whereColumn('lesson_blocks.id', 'file_sets.model_id');
                })
                ->delete();

            if ($deleted > 0) {
                $this->info("Cleaned {$deleted} orphan file_set rows.");
            }
        } catch (\Throwable $e) {
            $this->warn("FileSet cleanup skipped: {$e->getMessage()}");
        }
    }

    // ============================================================
    // Создание
    // ============================================================

    /**
     * Создаёт один чанк уроков в рамках одной транзакции.
     * Возвращает число реально созданных уроков (может быть < $n, если сработал стоп).
     *
     * Логика на урок:
     *   1. leaf таксономии уже известен — с ним пришли сюда (вместе с признаком
     *      наличия test_resolver у самой таксономии-листа).
     *   2. Информационные блоки: random(minBlocks..maxBlocks), order 0..N-1.
     *   3. Задания: random(minTests..maxTests). Если у листа есть resolver —
     *      половина обычных + половина процедурных; иначе только обычные.
     *   4. Обычные задания — из пула по листу (LessonBlock: lesson_id IS NULL,
     *      is_proc = false, привязан к листу). Процедурные — любые глобальные
     *      proc-задания. Берём сколько есть.
     *   5. Привязка заданий — через lesson_lesson_block_as_test; order
     *      продолжает нумерацию после информационных блоков.
     *   6. user_id урока: LESSON_OWNER_IDS по кругу, поровну.
     *   7. complexity урока — запекается сразу: avg(complexity заданий).
     */
    protected function createChunk(
        int $leafId,
        bool $hasResolver,
        int $n,
        $blocks,
        int $minBlocks,
        int $maxBlocks,
        int $minTests,
        int $maxTests,
    ): int {
        $created = 0;
        $ownerIds = $this->lessonOwnerIds;
        $ownerCount = count($ownerIds);

        // Обычные задания, доступные для этого листа.
        $commonPool = $this->commonTestsByTaxonomy[$leafId] ?? [];
        // Процедурные задания (общий пул).
        $procPool = $this->procTests;

        try {
            DB::transaction(function () use (
                $leafId,
                $hasResolver,
                $n,
                $blocks,
                $minBlocks,
                $maxBlocks,
                $minTests,
                $maxTests,
                $commonPool,
                $procPool,
                $ownerIds,
                $ownerCount,
                &$created
            ) {
                $now = now();

                for ($i = 0; $i < $n; $i++) {
                    if ($this->shouldStop()) {
                        break; // текущий урок ещё не начат — безопасно
                    }

                    // --- владелец: по кругу ---
                    $userId = $ownerIds[$i % $ownerCount];

                    $ts = $now->copy()->subMinutes(random_int(0, 60 * 24 * 90));

                    // Для timestamptz-колонок обязателен явный offset (P), иначе
                    // PG интерпретирует наивную строку в TZ сессии — «плавающее» время.
                    $tsStr = $ts->format('Y-m-d H:i:s P');

                    // --- 1. Определяем состав заданий ---
                    $testsTotal = random_int($minTests, $maxTests);
                    if ($hasResolver) {
                        // Поровну; на нечётном лишнее уходит процедурным.
                        $commonWanted = intdiv($testsTotal, 2);
                        $procWanted   = $testsTotal - $commonWanted;
                    } else {
                        $commonWanted = $testsTotal;
                        $procWanted   = 0;
                    }

                    // Берём сколько есть, не добиваем из другого пула.
                    $commonIds = $this->sampleUnique($commonPool, $commonWanted);
                    $procIds   = $this->sampleUnique($procPool, $procWanted);

                    // complexity урока — avg по всем привязанным заданиям.
                    $complexity = $this->avgComplexity($commonIds, $procIds);

                    // --- 2. Урок ---
                    $lessonId = DB::table('lessons')->insertGetId([
                        'user_id'     => $userId,
                        'locale'      => 'ru',
                        'saved'       => true,
                        'title'       => $this->pick($this->lessonTitles),
                        'description' => $this->pick($this->lessonDescriptions),
                        'published'   => true,
                        'complexity'  => $complexity,
                        'created_at'  => $tsStr,
                        'updated_at'  => $tsStr,
                    ]);

                    // --- 3. Информационные блоки ---
                    $blockCount = random_int($minBlocks, $maxBlocks);

                    for ($j = 0; $j < $blockCount; $j++) {
                        /** @var Block $block */
                        $block = $blocks->random();
                        $settings = $this->buildSettingsForBlock($block);

                        $this->pendingBlocks[] = [
                            'user_id'    => $userId,
                            'block_id'   => $block->id,
                            'lesson_id'  => $lessonId,
                            'order'      => $j,
                            'is_proc'    => false,
                            'settings'   => json_encode(
                                $settings,
                                JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
                            ),
                            'created_at' => $tsStr,
                            'updated_at' => $tsStr,
                        ];

                        if (count($this->pendingBlocks) >= $this->pivotBufferLimit) {
                            $this->flushBuffers();
                        }
                    }

                    // --- 4. Задания (pivot order продолжает после info-блоков) ---
                    $order = $blockCount;
                    foreach (array_merge($commonIds, $procIds) as $testId) {
                        $this->pendingPivots[] = [
                            'lesson_id'       => $lessonId,
                            'lesson_block_id' => $testId,
                            'order'           => $order++,
                            'created_at'      => $tsStr,
                            'updated_at'      => $tsStr,
                        ];

                        if (count($this->pendingPivots) >= $this->pivotBufferLimit) {
                            $this->flushBuffers();
                        }
                    }

                    // --- 5. Таксономия урока ---
                    $this->pendingLessonsTax[] = [
                        'lesson_id'   => $lessonId,
                        'taxonomy_id' => $leafId,
                        'created_at'  => $tsStr,
                        'updated_at'  => $tsStr,
                    ];

                    if (count($this->pendingLessonsTax) >= $this->pivotBufferLimit) {
                        $this->flushBuffers();
                    }

                    $created++;
                }

                // Всегда сбрасываем буфер внутри транзакции — иначе уроки без блоков.
                $this->flushBuffers();
            });
        } catch (\Throwable $e) {
            // Транзакция откатилась — сбрасываем буферы, чтобы не тащить
            // «мусорные» строки в следующий чанк.
            $this->pendingBlocks = [];
            $this->pendingPivots = [];
            $this->pendingLessonsTax = [];
            throw $e;
        }

        return $created;
    }

    /**
     * Уникальная выборка до $want элементов из пула.
     * Если в пуле меньше — возвращает сколько есть (без ошибки).
     *
     * @param array<int, int> $pool
     * @return array<int, int>
     */
    protected function sampleUnique(array $pool, int $want): array
    {
        if ($want <= 0 || empty($pool)) {
            return [];
        }

        if ($want >= count($pool)) {
            return $pool;
        }

        $keys = (array) array_rand($pool, $want);

        return array_map(static fn ($k) => $pool[$k], $keys);
    }

    /**
     * Средняя complexity по всем заданиям, которые будут привязаны к уроку.
     * Задания без complexity — игнорируются. Если нет ни одного значения — null.
     *
     * @param array<int, int> $commonIds
     * @param array<int, int> $procIds
     */
    protected function avgComplexity(array $commonIds, array $procIds): ?float
    {
        $testIds = array_merge($commonIds, $procIds);
        if (empty($testIds)) {
            return null;
        }

        $values = LessonBlock::query()
            ->whereIn('id', $testIds)
            ->pluck('complexity')
            ->filter(static fn ($v) => $v !== null)
            ->map(static fn ($v) => (float) $v);

        return $values->isEmpty() ? null : (float) $values->avg();
    }

    protected function flushBuffers(): void
    {
        if (!empty($this->pendingBlocks)) {
            DB::table('lesson_blocks')->insert($this->pendingBlocks);
            $this->pendingBlocks = [];
        }
        if (!empty($this->pendingPivots)) {
            DB::table('lesson_lesson_block_as_test')->insert($this->pendingPivots);
            $this->pendingPivots = [];
        }
        if (!empty($this->pendingLessonsTax)) {
            DB::table('lesson_taxonomy')->insert($this->pendingLessonsTax);
            $this->pendingLessonsTax = [];
        }
    }

    // ============================================================
    // Сборка settings для блока
    // ============================================================

    /**
     * Полный клон настроек блока-прототипа с подменой default
     * только у контентных узлов (title / summary / text / htmltext).
     * Галереи и image-узлы не изменяются.
     */
    protected function buildSettingsForBlock(Block $block): array
    {
        // 1. «Прототип»: настройки самого блока; если пусто — сериализованная схема.
        $protoSettings = $block->settings;
        if (!is_array($protoSettings) || empty($protoSettings)) {
            $protoSettings = $this->schemaCache[$block->code] ?? [];
        }
        if (empty($protoSettings)) {
            return [];
        }

        // 2. Полный клон настроек прототипа.
        //    В PHP массивы копируются по значению (copy-on-write),
        //    поэтому обычного присваивания достаточно для полного клона.
        $newSettings = $protoSettings;

        // 3. Заполняем ТОЛЬКО контентные узлы: title / summary / text / htmltext.
        //    Галереи, image-узлы и всё остальное — без изменений.
        $newSettings = $this->fillContentDefaultsOnly($newSettings);

        // 4. Прогон через нормализатор: остаются только public-узлы
        //    с их default. Форма гарантированно совпадает (клон),
        //    но на всякий случай ловим исключения.
        try {
            return SettingsNormalizer::extractPublicDefaults($newSettings, $protoSettings);
        } catch (SettingsShapeException $e) {
            $this->newLine();
            $this->warn("  ! Block {$block->id} ({$block->code}) shape: " . $e->getMessage());
            return [];
        } catch (\Throwable $e) {
            $this->newLine();
            $this->warn("  ! Block {$block->id} ({$block->code}): " . $e->getMessage());
            return [];
        }
    }

    /**
     * Рекурсивно обходит дерево настроек и перезаписывает default
     * ТОЛЬКО у контентных узлов.
     *
     * Обрабатываемые узлы:
     *  - key='title'    → blockTitles
     *  - key='summary'  → blockSummaries
     *  - key='text'     → randomPlainText()
     *  - key='htmltext' или type='htmltext' → randomHtml()
     *
     * Правила:
     *  - если у узла явно указан type и он не 'string' (и не 'htmltext'),
     *    узел считается контейнером и не трогается;
     *  - если type отсутствует (settings уже в «сокращённой» форме
     *    от extractPublicDefaults) — обрабатываем по key;
     *  - image-узлы и галереи не изменяем вообще.
     */
    protected function fillContentDefaultsOnly(array $node): array
    {
        // Сначала обходим детей — порядок не важен, но так читается проще.
        if (!empty($node['children']) && is_array($node['children'])) {
            foreach ($node['children'] as $i => $child) {
                if (is_array($child)) {
                    $node['children'][$i] = $this->fillContentDefaultsOnly($child);
                }
            }
        }

        $key  = $node['key']  ?? null;
        $type = $node['type'] ?? null;

        // htmltext — по ключу узла или по типу узла.
        $isHtmltext = ($key === 'htmltext') || ($type === 'htmltext');

        if ($isHtmltext) {
            $node['default'] = $this->randomHtml();
            return $node;
        }

        // Явный не-string тип — контейнер, не контентный лист. Пропускаем.
        if ($type !== null && $type !== 'string') {
            return $node;
        }

        switch ($key) {
            case 'title':
                $node['default'] = $this->pick($this->blockTitles);
                break;
            case 'summary':
                $node['default'] = $this->pick($this->blockSummaries);
                break;
            case 'text':
                $node['default'] = $this->randomPlainText();
                break;
        }

        return $node;
    }

