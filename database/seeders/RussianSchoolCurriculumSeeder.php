    private int $userId = 1;

    public function run(): void
    {
        DB::transaction(function () {
            $this->removeExistingTree();

            $root = $this->makeNode(null, 0, 'Школьная программа РФ', 'Классификация школьных образовательных программ РФ по предметам и классам');

            $stageOrder = 0;
            foreach ($this->curriculum() as $stageTitle => $stage) {
                $stageNode = $this->makeNode($root->id, $stageOrder++, $stageTitle, $stage['description'] ?? null);

                $subjectOrder = 0;
                foreach ($stage['subjects'] as $subjectTitle => $grades) {
                    $subjectNode = $this->makeNode($stageNode->id, $subjectOrder++, $subjectTitle);

                    $gradeOrder = 0;
                    foreach ($grades as $grade => $topics) {
                        $gradeNode = $this->makeNode($subjectNode->id, $gradeOrder++, "{$grade} класс");

                        $topicOrder = 0;
                        foreach ($topics as $topic) {
                            $this->makeNode($gradeNode->id, $topicOrder++, $topic);
                        }
                    }
                }
            }

            $this->command->info('✔ Школьная программа РФ успешно создана.');
        });
    }

    private function makeNode(?int $parentId, int $order, string $title, ?string $description = null): Taxonomy
    {
        $node = Taxonomy::create([
            'parent_id' => $parentId ?? -1,
            'user_id'   => $this->userId,
            'order'     => $order,
        ]);

        $node->translations()->create([
            'locale'      => 'ru',
            'title'       => $title,
            'description' => $description,
        ]);

        return $node;
    }

    private function removeExistingTree(): void
    {
        $root = Taxonomy::query()
            ->where('parent_id', -1)
            ->whereHas('translations', fn ($q) => $q
                ->where('locale', 'ru')
                ->where('title', 'Школьная программа РФ'))
            ->first();

        if ($root) {
            $this->deleteSubtree($root);
        }
    }

    private function deleteSubtree(Taxonomy $node): void
    {
        foreach ($node->children()->get() as $child) {
            $this->deleteSubtree($child);
        }
        $node->translations()->delete();
        $node->delete();
    }

