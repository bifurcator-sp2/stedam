    public function run(): void
    {
        $existing = DB::table('lessons')
            ->where('user_id', $this->userId)
            ->count();
        if ($existing >= 1000) {
            $this->command->warn(
                "User {$this->userId} already has {$existing} lessons. ".
                "Aborting to avoid duplicates. Truncate first if this is intentional."
            );
            return;
        }

        $leaves = $this->leafIds();
        $leafCount = count($leaves);
        if ($leafCount === 0) {
            $this->command->error("No leaf taxonomies found for user {$this->userId}");
            return;
        }
        $this->command->info("Leaves: {$leafCount}, target lessons: {$this->totalLessons}");

        $distribution = $this->distribute($this->totalLessons, $leafCount);
        $bar = $this->command->getOutput()->createProgressBar($this->totalLessons);
        $bar->start();

        $created = 0;

        foreach ($leaves as $index => $leafId) {
            $count = $distribution[$index];
            if ($count <= 0) continue;

            for ($offset = 0; $offset < $count; $offset += $this->chunkSize) {
                $chunk = min($this->chunkSize, $count - $offset);
                $this->createChunk($leafId, $chunk);
                $created += $chunk;
                $bar->advance($chunk);
            }
        }

        $bar->finish();
        $this->command->newLine(2);
        $this->command->info("Done. Created {$created} lessons, ".
            "with ~".($created * ($this->minBlocks + $this->maxBlocks) / 2)." blocks.");
    }

    // ============================================================
    // Создание
    // ============================================================

    protected function createChunk(int $leafId, int $n): void
    {
        $now = now();
        $pivotRows = [];

        for ($i = 0; $i < $n; $i++) {
            $ts = $now->copy()->subMinutes(random_int(0, 60 * 24 * 30));

            $lessonId = DB::table('lessons')->insertGetId([
                'user_id'     => $this->userId,
                'locale'      => 'ru',
                'saved'       => true,
                'title'       => $this->pick($this->lessonTitles),
                'description' => $this->pick($this->lessonDescriptions),
                'published'   => true,
                'created_at'  => $ts,
                'updated_at'  => $ts,
            ]);

            $blockCount = random_int($this->minBlocks, $this->maxBlocks);
            $blockRows = [];
            for ($j = 0; $j < $blockCount; $j++) {
                $blockRows[] = [
                    'user_id'    => $this->userId,
                    'block_id'   => $this->blockId,
                    'lesson_id'  => $lessonId,
                    'order'      => $j,
                    'settings'   => json_encode(
                        $this->buildSettings(),
                        JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
                    ),
                    'created_at' => $ts,
                    'updated_at' => $ts,
                ];
            }
            DB::table('lesson_blocks')->insert($blockRows);

            $pivotRows[] = [
                'lesson_id'   => $lessonId,
                'taxonomy_id' => $leafId,
            ];
        }

        DB::table('lesson_taxonomy')->insert($pivotRows);
    }

