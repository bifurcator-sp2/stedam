    // Утилиты
    // ============================================================

    protected function leafIds(): array
    {
        return DB::table('taxonomies')
            ->whereNull('deleted_at')
            ->where('user_id', $this->userId)
            ->whereNotExists(function ($q) {
                $q->select(DB::raw(1))
                    ->from('taxonomies as t_child')
                    ->whereColumn('t_child.parent_id', 'taxonomies.id')
                    ->whereNull('t_child.deleted_at');
            })
            ->orderBy('id')
            ->pluck('id')
            ->all();
    }

    protected function distribute(int $total, int $buckets): array
    {
        $base = intdiv($total, $buckets);
        $rem  = $total % $buckets;
        $arr  = array_fill(0, $buckets, $base);
        for ($i = 0; $i < $rem; $i++) {
            $arr[$i]++;
        }
        return $arr;
    }

    protected function randomText(int $min = 3, int $max = 6): string
    {
        $n = random_int($min, $max);
        $parts = [];
        for ($i = 0; $i < $n; $i++) {
            $parts[] = rtrim($this->pick($this->blockSentences), '.!?');
        }
        return implode('. ', $parts) . '.';
    }

    protected function pick(array $arr)
    {
        return $arr[array_rand($arr)];
    }
