    protected function replaceTextDefaults(array $node): array
    {
        if (($node['public'] ?? false) === true && isset($node['key'])) {
            switch ($node['key']) {
                case 'title':
                    $node['default'] = $this->pick($this->blockTitles);
                    break;
                case 'summary':
                    $node['default'] = $this->pick($this->blockSummaries);
                    break;
                case 'text':
                    $node['default'] = $this->randomText(3, 6);
                    break;
            }
        }
        if (!empty($node['children']) && is_array($node['children'])) {
            foreach ($node['children'] as $idx => $child) {
                if (is_array($child)) {
                    $node['children'][$idx] = $this->replaceTextDefaults($child);
                }
            }
        }
        return $node;
    }

