    private int $userId = 1;

    public function run(): void
    {
        DB::transaction(function () {
            $this->removeExistingTree();

            $root = $this->makeNode(null, 0, 'Высшее образование РФ', 'Классификация программ высшего образования РФ по уровням, направлениям подготовки и дисциплинам');

            $levelOrder = 0;
            foreach ($this->curriculum() as $levelTitle => $level) {
                $levelNode = $this->makeNode($root->id, $levelOrder++, $levelTitle, $level['description'] ?? null);

                $groupOrder = 0;
                foreach ($level['groups'] as $groupTitle => $programs) {
                    $groupNode = $this->makeNode($levelNode->id, $groupOrder++, $groupTitle);

                    $programOrder = 0;
                    foreach ($programs as $programTitle => $courses) {
                        $programNode = $this->makeNode($groupNode->id, $programOrder++, $programTitle);

                        $courseOrder = 0;
                        foreach ($courses as $course => $disciplines) {
                            $courseNode = $this->makeNode($programNode->id, $courseOrder++, $course);

                            $disciplineOrder = 0;
                            foreach ($disciplines as $discipline) {
                                $this->makeNode($courseNode->id, $disciplineOrder++, $discipline);
                            }
                        }
                    }
                }
            }

            $this->command->info('✔ Высшее образование РФ успешно создано.');
        });
    }

    private function makeNode(?int $parentId, int $order, string $title, ?string $description = null): Taxonomy
    {
        $node = Taxonomy::create([
            'parent_id' => $parentId ?? -1,
            'user_id'   => $this->userId,
            'order'     => $order,
        ]);

        $node->translations()->create([
            'locale'      => 'ru',
            'title'       => $title,
            'description' => $description,
        ]);

        return $node;
    }

    private function removeExistingTree(): void
    {
        $root = Taxonomy::query()
            ->where('parent_id', -1)
            ->whereHas('translations', fn ($q) => $q
                ->where('locale', 'ru')
                ->where('title', 'Высшее образование РФ'))
            ->first();

        if ($root) {
            $this->deleteSubtree($root);
        }
    }

    private function deleteSubtree(Taxonomy $node): void
    {
        foreach ($node->children()->get() as $child) {
            $this->deleteSubtree($child);
        }
        $node->translations()->delete();
        $node->delete();
    }

